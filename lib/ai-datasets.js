'use strict';
// Dataset register for the ISO/IEC 42001 programme (migration 076).
//
// Each dataset an AI system is built or run on, with what Annex A.7 asks the
// organisation to know about it: how it was obtained and selected (A.7.3),
// the quality it must meet and the last check against that (A.7.4), how its
// provenance is recorded (A.7.5) and how it is prepared (A.7.6). The fields
// beside those follow the data documentation A.4.3 describes: categories,
// labelling, known bias, retention and when it last changed. A dataset is
// linked to the systems that use it, and for what, so the auditor's list of
// datasets is a query over the register.

const { RegisterError } = require('./ai-systems');

const SOURCE_TYPES = Object.freeze({
  internal: 'Collected by the organisation',
  customer: 'Provided by customers',
  purchased: 'Bought or licensed',
  partner: 'Shared by a partner',
  open: 'Open or public data',
  synthetic: 'Synthetic or generated',
});
const REFRESH = Object.freeze({
  fixed: 'A fixed snapshot',
  periodic: 'Refreshed periodically',
  streamed: 'Streamed continuously',
  generated: 'Generated by a system',
});
const PERSONAL = Object.freeze({
  unknown: 'Not yet determined',
  none: 'No personal data',
  personal: 'Personal data',
  sensitive: 'Sensitive personal data',
});
const USES = Object.freeze({
  training: 'Training',
  validation: 'Validation',
  testing: 'Testing',
  production: 'Production input',
  reference: 'Reference or lookup',
});
// Free-text fields in form order: key, label, hint, the Annex A control it answers.
const TEXT_FIELDS = Object.freeze([
  ['description', 'What it holds', 'In a sentence or two: what the records are and what they describe.', null],
  ['data_categories', 'Categories of data', 'Kinds of data in it, such as transactions, images, free text or sensor readings, and for machine learning which part is used for training, validation and testing.', 'A.4.3'],
  ['data_rights', 'Rights to use it', 'The licence, contract, consent or other basis for using it, including any copyright or personal data limits.', 'A.7.3'],
  ['acquisition', 'How it was obtained and selected', 'Where it came from, how much was taken, why this data and not other data, and how it was handled before.', 'A.7.3'],
  ['quality_requirements', 'Quality it must meet', 'Completeness, accuracy, how representative it must be of the people and situations the system meets, and any thresholds.', 'A.7.4'],
  ['quality_result', 'Result of the last quality check', 'What was checked, against which requirement, and what was found.', 'A.7.4'],
  ['provenance', 'How its provenance is recorded', 'How the record of where it came from, and every change, transfer and transformation since, is kept and verified.', 'A.7.5'],
  ['preparation', 'How it is prepared', 'Cleaning, filling gaps, normalising, encoding and the like, and why those methods were chosen.', 'A.7.6'],
  ['labelling', 'How it is labelled', 'Who labels it, against what guide, and how label quality is checked. Leave blank if it is not labelled.', 'A.4.3'],
  ['known_bias', 'Known or suspected bias', 'Groups or situations under- or over-represented, and what is done about it.', 'A.4.3'],
  ['retention', 'Retention and disposal', 'How long it is kept and how it is disposed of.', 'A.4.3'],
]);
// The four records Annex A.7 expects for a dataset.
const A7_RECORDS = Object.freeze([
  ['acquisition', 'Acquisition', 'A.7.3'],
  ['quality', 'Quality check', 'A.7.4'],
  ['provenance', 'Provenance', 'A.7.5'],
  ['preparation', 'Preparation', 'A.7.6'],
]);

function clean(value, max = 8000) {
  const text = String(value == null ? '' : value).replace(/\r\n?/g, '\n').trim();
  if (text.length > max) throw new RegisterError(`Keep this to ${max.toLocaleString()} characters or fewer.`);
  return text || null;
}

function validDate(value, label) {
  if (value == null || value === '') return null;
  const text = String(value).trim();
  if (!/^\d{4}-\d{2}-\d{2}$/.test(text) || Number.isNaN(Date.parse(`${text}T00:00:00Z`))) throw new RegisterError(`Enter a valid ${label}.`);
  return text;
}

const pick = (value, allowed, fallback = null) => (Object.prototype.hasOwnProperty.call(allowed, value) ? value : fallback);

// Which of the four A.7 records a dataset has.
function a7(d) {
  const has = {
    acquisition: !!d.acquisition,
    quality: !!(d.quality_requirements && d.quality_checked_on),
    provenance: !!d.provenance,
    preparation: !!d.preparation,
  };
  return { has, count: Object.values(has).filter(Boolean).length, total: A7_RECORDS.length };
}

function input(body) {
  const name = clean(body.name, 160);
  if (!name) throw new RegisterError('Name the dataset.');
  const values = {
    name,
    source_type: pick(body.source_type, SOURCE_TYPES),
    origin: clean(body.origin, 300),
    refresh: pick(body.refresh, REFRESH),
    personal_data: pick(body.personal_data, PERSONAL, 'unknown'),
    quality_checked_on: validDate(body.quality_checked_on, 'quality check date'),
    last_changed: validDate(body.last_changed, 'date it last changed'),
    owner: clean(body.owner, 160),
  };
  for (const [key] of TEXT_FIELDS) values[key] = clean(body[key]);
  if (values.quality_checked_on && !values.quality_result) throw new RegisterError('Record what the quality check found.');
  return values;
}

const COLUMNS = ['name', 'source_type', 'origin', 'refresh', 'personal_data', 'quality_checked_on', 'last_changed', 'owner', ...TEXT_FIELDS.map(([k]) => k)];

function list(db, ws) {
  const uses = db.prepare(`SELECT sd.dataset_id, sd.use, s.id AS system_id, s.name AS system_name, s.in_scope FROM ai_system_datasets sd
    JOIN ai_systems s ON s.id = sd.ai_system_id WHERE sd.workspace_id=? ORDER BY s.name`).all(ws.id);
  return db.prepare('SELECT * FROM ai_datasets WHERE workspace_id=? ORDER BY name').all(ws.id).map((d) => {
    const mine = uses.filter((u) => u.dataset_id === d.id);
    const systems = [...new Map(mine.map((u) => [u.system_id, { id: u.system_id, name: u.system_name, in_scope: u.in_scope }])).values()];
    return { ...d, uses: mine, systems, inScopeUse: mine.some((u) => u.in_scope), a7: a7(d) };
  });
}

function load(db, ws, id) {
  return db.prepare('SELECT * FROM ai_datasets WHERE id=? AND workspace_id=?').get(Number(id), ws.id) || null;
}

function detail(db, ws, id) {
  const dataset = load(db, ws, id);
  if (!dataset) return null;
  const uses = db.prepare(`SELECT sd.use, sd.linked_at, s.id AS system_id, s.name AS system_name, s.in_scope, s.lifecycle_stage
    FROM ai_system_datasets sd JOIN ai_systems s ON s.id = sd.ai_system_id WHERE sd.dataset_id=? AND sd.workspace_id=? ORDER BY s.name, sd.use`).all(dataset.id, ws.id);
  const systems = db.prepare('SELECT id, name FROM ai_systems WHERE workspace_id=? ORDER BY name').all(ws.id);
  return { dataset: { ...dataset, a7: a7(dataset) }, uses, systems };
}

function create(db, ws, actorId, body) {
  const v = input(body);
  if (db.prepare('SELECT 1 FROM ai_datasets WHERE workspace_id=? AND name=?').get(ws.id, v.name)) throw new RegisterError(`${v.name} is already on the register.`);
  return Number(db.prepare(`INSERT INTO ai_datasets (workspace_id, ${COLUMNS.join(', ')}, created_by)
    VALUES (?, ${COLUMNS.map(() => '?').join(', ')}, ?)`).run(ws.id, ...COLUMNS.map((c) => v[c]), actorId).lastInsertRowid);
}

function update(db, ws, id, body) {
  const dataset = load(db, ws, id);
  if (!dataset) throw new RegisterError('Dataset not found.', 404);
  if (Number(body.version) !== Number(dataset.version)) throw new RegisterError('This dataset was changed in another session. Refresh and try again.', 409);
  const v = input(body);
  if (v.name !== dataset.name && db.prepare('SELECT 1 FROM ai_datasets WHERE workspace_id=? AND name=? AND id!=?').get(ws.id, v.name, dataset.id)) {
    throw new RegisterError(`${v.name} is already on the register.`);
  }
  db.prepare(`UPDATE ai_datasets SET ${COLUMNS.map((c) => `${c}=?`).join(', ')}, updated_at=datetime('now'), version=version+1
    WHERE id=? AND workspace_id=? AND version=?`).run(...COLUMNS.map((c) => v[c]), dataset.id, ws.id, dataset.version);
}

function remove(db, ws, id) {
  const r = db.prepare('DELETE FROM ai_datasets WHERE id=? AND workspace_id=?').run(Number(id), ws.id);
  if (!r.changes) throw new RegisterError('Dataset not found.', 404);
}

// Record that a system uses a dataset for a purpose. Both must be this
// client's; the database refuses a link across clients as well.
function link(db, ws, actorId, systemId, datasetId, use) {
  const system = db.prepare('SELECT id FROM ai_systems WHERE id=? AND workspace_id=?').get(Number(systemId), ws.id);
  const dataset = load(db, ws, datasetId);
  if (!system || !dataset) throw new RegisterError('Choose an AI system and a dataset of this client.');
  const purpose = pick(use, USES);
  if (!purpose) throw new RegisterError('Say what the system uses the dataset for.');
  db.prepare(`INSERT OR IGNORE INTO ai_system_datasets (ai_system_id, dataset_id, workspace_id, use, linked_by) VALUES (?, ?, ?, ?, ?)`)
    .run(system.id, dataset.id, ws.id, purpose, actorId);
}

function unlink(db, ws, systemId, datasetId, use) {
  db.prepare('DELETE FROM ai_system_datasets WHERE ai_system_id=? AND dataset_id=? AND use=? AND workspace_id=?')
    .run(Number(systemId), Number(datasetId), String(use), ws.id);
}

// The datasets one system uses, and the ones it could still be linked to.
function forSystem(db, ws, systemId) {
  const linked = db.prepare(`SELECT d.id, d.name, d.personal_data, d.acquisition, d.quality_requirements, d.quality_checked_on, d.provenance, d.preparation, sd.use
    FROM ai_system_datasets sd JOIN ai_datasets d ON d.id = sd.dataset_id WHERE sd.ai_system_id=? AND sd.workspace_id=? ORDER BY d.name, sd.use`)
    .all(Number(systemId), ws.id).map((d) => ({ ...d, a7: a7(d) }));
  const all = db.prepare('SELECT id, name FROM ai_datasets WHERE workspace_id=? ORDER BY name').all(ws.id);
  return { linked, all };
}

module.exports = {
  SOURCE_TYPES, REFRESH, PERSONAL, USES, TEXT_FIELDS, A7_RECORDS, a7,
  list, load, detail, create, update, remove, link, unlink, forSystem,
};
